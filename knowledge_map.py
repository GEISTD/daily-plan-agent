# 知识点 -> 所属主题（用于反向统计，以及生成器的兜底逻辑）
KNOWLEDGE_TOPIC = {}
for _topic, (_main, _rel) in TOPIC_KNOWLEDGE.items():
    KNOWLEDGE_TOPIC.setdefault(_main, _topic)
    for _r in _rel:
        KNOWLEDGE_TOPIC.setdefault(_r, _topic)


def knowledge_for(qnum, topic):
    """返回 (主知识点, [相关知识点])；题号覆盖优先于主题映射。"""
    qnum = int(qnum)
    if qnum in QUESTION_KNOWLEDGE:
        return QUESTION_KNOWLEDGE[qnum]
    if topic in TOPIC_KNOWLEDGE:
        return TOPIC_KNOWLEDGE[topic]
    # 兜底：主题名本身当知识点，保证不会因为新增主题而崩
    return (topic, [])


def links_for(qnum, topic, include_related=True):
    """返回可直接拼进 Markdown 的双链列表。"""
    main, related = knowledge_for(qnum, topic)
    out = [f"[[{main}]]"]
    if include_related:
        for r in related:
            if r != main:
                out.append(f"[[{r}]]")
    return out


def main_knowledge(qnum, topic):
    return knowledge_for(qnum, topic)[0]
